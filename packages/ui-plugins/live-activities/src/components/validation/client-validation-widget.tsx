// Utility functions
const getHealthStatus = (status: ClientValidationStatus | string | boolean): HealthStatus => {
  return !status ? 'valid' : 'invalid';
};

const getStatusMessage = (status: ClientValidationStatus | string | boolean): string => {
  if (!status) return STATUS_MESSAGES.false;
  if (String(status).indexOf('messaging-not-installed') !== -1) {
    return STATUS_MESSAGES['messaging-not-installed'];
  }
  if (String(status).indexOf('no-token') !== -1) {
    return STATUS_MESSAGES['no-token'];
  }
  return STATUS_MESSAGES[status as keyof typeof STATUS_MESSAGES] || '';
};

const getStatusDetails = (status: ClientValidationStatus | string | boolean): string | undefined => {
  return STATUS_DETAILS[status as keyof typeof STATUS_DETAILS];
};


