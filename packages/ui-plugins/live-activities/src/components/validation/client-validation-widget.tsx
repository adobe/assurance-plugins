/**
 * Renders client validation widget with device information and status details.
 */
const ClientValidationWidget: React.FC<ClientValidationWidgetProps> = ({ ...extraProps }) => {
  const ecid = useECID();
  const token = useSelectedClientPushToken();
  const status = useClientValidationStatus();
  const isLoading = status === 'loading';
  const { openExpUrl } = useOpenExperienceUrl();

  // Data rows for ECID and Push Token
  const dataRows: DataRow[] = [
    {
      label: BUTTON_LABELS.ecid,
      value: ecid,
      showCopy: true
    },
    {
      label: BUTTON_LABELS.token,
      value: token,
      showCopy: true,
      isLongData: true
    }
  ];

  const statusMessage = getStatusMessage(status);
  const healthStatus = getHealthStatus(status);

  return (
    <View>
      <Card {...extraProps}>
        <Heading marginTop="size-0">Client</Heading>
        {isLoading ? (
          <Flex justifyContent="center" alignItems="center" height="100px">
            <ProgressCircle aria-label="Loading…" isIndeterminate />
          </Flex>
        ) : (
          <>
            <Text>This is the messaging details found in the client at the time of the connection to this Assurance session.</Text>
            <Flex gap="size-100" alignItems="center" marginTop="size-200">
              {getHealthIcon(healthStatus, 'L')}
              <Heading level={4}>{statusMessage}</Heading>
            </Flex>
            
            <View marginTop="size-200">
              <StatusDetailsRenderer
                status={status}
                openExpUrl={openExpUrl}
              />
            </View>
            
            <table style={{ width: '100%', borderCollapse: 'collapse', marginTop: 16 }}>
              <tbody>
                {dataRows.map(row => (
                  <tr key={row.label} style={{ borderBottom: '1px solid #e1e1e1' }}>
                    <td style={{ fontWeight: 500, padding: '12px 16px' }}>{row.label}</td>
                    <td
                      style={{
                        padding: '12px 16px',
                        maxWidth: row.isLongData ? 300 : undefined,
                        wordBreak: row.isLongData ? 'break-all' : undefined
                      }}
                    >
                      {row.showCopy ? <CopyableValue value={row.value} /> : renderValue(row.value)}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>  
            
            {/* Live Activities Validation Section */}
            <View marginTop="size-300">
              <View paddingTop="size-200">
                <LiveActivitiesValidationSection />
              </View>
            </View>
          </>
        )}
      </Card>
    </View>
  );
};

export default ClientValidationWidget;
